"""Train and evaluate the Random Forest detector on SYNTHETIC data.

Usage:  python train_model.py
All reported scores are results on synthetic simulation data only; they do NOT
describe real-world IoT/IIoT ransomware detection performance.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import joblib
import matplotlib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (accuracy_score, classification_report, confusion_matrix, f1_score,
                             precision_score, recall_score)
from sklearn.model_selection import GroupKFold, cross_val_score

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from src.data_generator import DATA_NOTICE, SEED, write_dataset  # noqa: E402
from src.detector import BASELINE_FILE, FEATURE_FILE, MODEL_FILE, Detector  # noqa: E402
from src.feature_engineering import CLASS_NAMES, FEATURES  # noqa: E402

SYNTH_NOTE = ("These metrics come from a held-out SYNTHETIC test set generated by this project. "
              "They show behaviour inside the simulation only, not real-world detection performance.")
NAVY, TEAL, GREEN, RED = "#0b1b33", "#14b8a6", "#22c55e", "#ef4444"


def metrics_from(y_true, y_pred) -> dict:
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    return dict(
        accuracy=float(accuracy_score(y_true, y_pred)),
        precision=float(precision_score(y_true, y_pred, zero_division=0)),
        recall=float(recall_score(y_true, y_pred, zero_division=0)),
        f1=float(f1_score(y_true, y_pred, zero_division=0)),
        false_positive_rate=float(fp / (fp + tn)) if (fp + tn) else 0.0,
        false_negative_rate=float(fn / (fn + tp)) if (fn + tp) else 0.0,
        tn=int(tn), fp=int(fp), fn=int(fn), tp=int(tp), n=int(len(y_true)),
    )


def plot_confusion(m: dict, path: Path, title: str) -> None:
    cm = np.array([[m["tn"], m["fp"]], [m["fn"], m["tp"]]])
    fig, ax = plt.subplots(figsize=(5.2, 4.4), facecolor=NAVY)
    ax.set_facecolor(NAVY)
    ax.imshow(cm, cmap="GnBu")
    ax.set_xticks([0, 1], [CLASS_NAMES[0], CLASS_NAMES[1]], color="white", fontsize=8)
    ax.set_yticks([0, 1], [CLASS_NAMES[0], CLASS_NAMES[1]], color="white", fontsize=8)
    ax.set_xlabel("Predicted", color="white")
    ax.set_ylabel("Actual", color="white")
    for i in range(2):
        for j in range(2):
            ax.text(j, i, str(cm[i, j]), ha="center", va="center", fontsize=16, fontweight="bold",
                    color="black" if cm[i, j] > cm.max() / 2 else "white")
    ax.set_title(title, color="white", fontsize=10)
    fig.text(0.5, 0.01, "Synthetic test data only", color=TEAL, ha="center", fontsize=8)
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(path, dpi=150, facecolor=NAVY)
    plt.close(fig)


def plot_importance(imp: dict, path: Path) -> None:
    items = sorted(imp.items(), key=lambda kv: kv[1])
    fig, ax = plt.subplots(figsize=(6, 3.8), facecolor=NAVY)
    ax.set_facecolor(NAVY)
    ax.barh([k for k, _ in items], [v for _, v in items], color=TEAL)
    ax.tick_params(colors="white", labelsize=8)
    ax.set_title("Random Forest feature importance (synthetic data)", color="white", fontsize=10)
    for s in ax.spines.values():
        s.set_color("#334155")
    fig.tight_layout()
    fig.savefig(path, dpi=150, facecolor=NAVY)
    plt.close(fig)


def train(root: Path = ROOT, seed: int = SEED, n_normal: int = 240, n_attack: int = 240, quiet: bool = False) -> dict:
    root = Path(root)
    data_dir, models_dir, eval_dir = root / "data" / "generated", root / "models", root / "evidence" / "evaluation"
    for d in (models_dir, eval_dir):
        d.mkdir(parents=True, exist_ok=True)
    parts = write_dataset(data_dir, seed, n_normal=n_normal, n_attack=n_attack)
    tr, va, te = parts["train"], parts["val"], parts["test"]

    rf = RandomForestClassifier(n_estimators=200, max_depth=12, min_samples_leaf=2, class_weight="balanced",
                                random_state=seed, n_jobs=-1)
    t0 = time.perf_counter()
    rf.fit(tr[FEATURES], tr["label"])
    train_s = time.perf_counter() - t0

    # Baseline of NORMAL behaviour per device (training split only) for the explanation step.
    base = {}
    for dev, g in tr[tr["label"] == 0].groupby("device_id"):
        base[dev] = {f: dict(mean=float(g[f].mean()), std=float(g[f].std(ddof=0))) for f in FEATURES}

    joblib.dump(rf, models_dir / MODEL_FILE)
    (models_dir / FEATURE_FILE).write_text(json.dumps(FEATURES, indent=2), encoding="utf-8")
    (models_dir / BASELINE_FILE).write_text(json.dumps(base, indent=2), encoding="utf-8")

    res = {}
    for name, d in (("train", tr), ("validation", va), ("test", te)):
        res[name] = metrics_from(d["label"], rf.predict(d[FEATURES]))
    # Grouped cross-validation on train+val (folds never split a scenario)
    tv = pd.concat([tr, va])
    cv = cross_val_score(RandomForestClassifier(n_estimators=100, max_depth=12, min_samples_leaf=2,
                                                class_weight="balanced", random_state=seed, n_jobs=-1),
                         tv[FEATURES], tv["label"], groups=tv["scenario_id"], cv=GroupKFold(5), scoring="f1")

    det = Detector.load(models_dir)
    sample = te.sample(200, random_state=seed)
    times = []
    for _, r in sample.iterrows():
        times.append(det.predict_window(r.to_dict(), r["device_id"])["inference_ms"])
    t1 = time.perf_counter()
    rf.predict(te[FEATURES])
    batch_ms = (time.perf_counter() - t1) * 1000.0 / len(te)

    out = dict(
        note=SYNTH_NOTE, data_notice=DATA_NOTICE, seed=seed, model="RandomForestClassifier(n_estimators=200, max_depth=12, "
        "min_samples_leaf=2, class_weight='balanced')", features=FEATURES, decision_threshold=0.5,
        sizes={k: dict(windows=len(v), scenarios=int(v["scenario_id"].nunique()), positives=int(v["label"].sum()))
               for k, v in parts.items()},
        train_seconds=round(train_s, 3), metrics=res,
        grouped_cv_f1_train_plus_val=dict(mean=float(cv.mean()), std=float(cv.std()), folds=[float(x) for x in cv]),
        inference_ms_single_window_mean=round(float(np.mean(times)), 3),
        inference_ms_single_window_p95=round(float(np.percentile(times, 95)), 3),
        inference_ms_batch_per_window=round(batch_ms, 4),
        feature_importance={k: round(v, 4) for k, v in det.importances.items()},
    )
    (eval_dir / "metrics.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    (eval_dir / "classification_report_test.txt").write_text(
        SYNTH_NOTE + "\n\n" + classification_report(te["label"], rf.predict(te[FEATURES]),
                                                    target_names=[CLASS_NAMES[0], CLASS_NAMES[1]], digits=4),
        encoding="utf-8")
    (eval_dir / "confusion_matrix_test.json").write_text(json.dumps(
        dict(labels=[CLASS_NAMES[0], CLASS_NAMES[1]], matrix=[[res["test"]["tn"], res["test"]["fp"]],
                                                              [res["test"]["fn"], res["test"]["tp"]]], note=SYNTH_NOTE), indent=2),
        encoding="utf-8")
    plot_confusion(res["test"], eval_dir / "confusion_matrix_test.png", "Confusion matrix – held-out synthetic test set")
    plot_importance(out["feature_importance"], eval_dir / "feature_importance.png")
    if not quiet:
        t = res["test"]
        print(SYNTH_NOTE)
        print(f"Train windows {len(tr)} | Val {len(va)} | Test {len(te)} (scenario-level split, no leakage)")
        for k in ("accuracy", "precision", "recall", "f1", "false_positive_rate", "false_negative_rate"):
            print(f"  TEST {k:22s} {t[k]:.4f}")
        print(f"  Confusion (TN FP FN TP): {t['tn']} {t['fp']} {t['fn']} {t['tp']}")
        print(f"  Validation F1 {res['validation']['f1']:.4f} | Grouped 5-fold CV F1 {cv.mean():.4f} +/- {cv.std():.4f}")
        print(f"  Inference (single window): {out['inference_ms_single_window_mean']} ms mean")
        print(f"Saved model to {models_dir / MODEL_FILE}")
    return out


if __name__ == "__main__":
    train()